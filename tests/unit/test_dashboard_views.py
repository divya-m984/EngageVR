def cells(table: object) -> str:
    """Every cell, caption, and title of a table as one lowercase string."""
    assert table is not None
    parts = [table.title, table.caption or ""]  # type: ignore[attr-defined]
    parts.extend(table.columns)  # type: ignore[attr-defined]
    for row in table.rows:  # type: ignore[attr-defined]
        parts.extend(row)
    return " ".join(parts).lower()


def row_text(table: object) -> str:
    """Only the data cells, headings, and title -- never the caption.

    Several captions deny a reading in the reading's own words ("not an
    improvement", "does not rank subjects"). A banned-word check over the
    whole table would trip on the denial, so the wording checks look at
    the data the reader actually reads as a result, and the denial is
    asserted separately.
    """
    assert table is not None
    parts = [table.title]  # type: ignore[attr-defined]
    parts.extend(table.columns)  # type: ignore[attr-defined]
    for row in table.rows:  # type: ignore[attr-defined]
        parts.extend(row)
    return " ".join(parts).lower()


