"""Dataset, quality, baseline, fusion, and personalization views.

Most of these tests are about wording, because on this dashboard the
wording is the safeguard.  A confusion matrix labelled *ground truth*, a
personalization delta labelled *improvement*, or a quality chart labelled
*engagement* would each be a scientific claim this repository cannot
support, and none of them would raise an exception on its own.
"""

from __future__ import annotations

