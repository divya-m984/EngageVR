"""Experiment schemas: splits, metrics, calibration, ablation, run manifests.

These models are the persisted form of a training run.  They are written
as JSON beside the run's artifacts so that a result can be inspected, and
its provenance judged, **without loading any model file** — which matters
because a pickled estimator is executable content and must never be
opened just to find out where a number came from.

Every metrics document carries an explicit evaluation mode.  A
``software_self_check`` result describes only whether this code works; it
is never a statement about people, and the disclaimer that says so is a
required field rather than a formatting convention.
"""

from __future__ import annotations

import enum
from datetime import datetime
from typing import Self

from pydantic import BaseModel, Field, model_validator

#: Banner printed and persisted for every synthetic run.
SOFTWARE_SELF_CHECK_BANNER = "SOFTWARE SELF-CHECK — NOT SCIENTIFIC EVALUATION"

#: Disclaimer attached to every metrics document produced from synthetic data.
SELF_CHECK_DISCLAIMER = (
    "SOFTWARE SELF-CHECK — NOT SCIENTIFIC EVALUATION. Every number in this "
    "document was computed from SYNTHETIC data generated by this repository "
    "from a known data-generating process. It measures whether the "
    "modelling pipeline is wired together correctly. It is NOT model "
    "accuracy, NOT engagement validity, NOT cognitive-load validity, NOT "
    "evidence about any person, and it must NEVER be compared with a "
    "published result on real data."
)


class EvaluationMode(enum.StrEnum):
    """Whether a run is a pipeline self-check or a scientific evaluation."""

    SOFTWARE_SELF_CHECK = "software_self_check"
    SCIENTIFIC = "scientific"


class RunStatus(enum.StrEnum):
    """Terminal state of a run."""

    COMPLETED = "completed"
    FAILED = "failed"


class SplitStrategy(enum.StrEnum):
    """Grouped cross-validation strategies this pipeline will use.

    Ungrouped strategies are deliberately absent.  When several rows share
    a participant or a session, ``KFold``, ``StratifiedKFold``, and
    ``train_test_split`` put windows from one person on both sides of the
    split, and the resulting score measures memorisation of that person.
    """

    STRATIFIED_GROUP_K_FOLD = "stratified_group_k_fold"
    GROUP_K_FOLD = "group_k_fold"


class GroupField(enum.StrEnum):
    """Column used to define independent groups."""

    SUBJECT_ID = "subject_id"
    SESSION_ID = "session_id"


class FoldAssignment(BaseModel):
    """Group and row membership for one outer fold.

    ``calibration_groups`` are carved out of the training groups, never out
    of ``test_groups``.  The three lists are disjoint by construction and
    :func:`engagevr.training.splits.audit_split` re-checks that they are.
    """

    model_config = {"extra": "forbid"}

    fold_index: int = Field(ge=0)
    train_groups: tuple[str, ...]
    calibration_groups: tuple[str, ...] = ()
    test_groups: tuple[str, ...]

    train_row_count: int = Field(ge=0)
    calibration_row_count: int = Field(default=0, ge=0)
    test_row_count: int = Field(ge=0)

    train_target_distribution: dict[str, int] | None = None
    test_target_distribution: dict[str, int] | None = None
    train_target_summary: dict[str, float] | None = None
    test_target_summary: dict[str, float] | None = None

    valid: bool = True
    invalid_reason: str | None = None
    warnings: tuple[str, ...] = ()

    @model_validator(mode="after")
    def _check(self) -> Self:
        train = set(self.train_groups)
        calibration = set(self.calibration_groups)
        test = set(self.test_groups)
        if train & test:
            raise ValueError(
                f"fold {self.fold_index}: groups appear in both train and test: "
                f"{sorted(train & test)}"
            )
        if calibration & test:
            raise ValueError(
                f"fold {self.fold_index}: groups appear in both calibration and "
                f"test: {sorted(calibration & test)}"
            )
        if calibration - train:
            raise ValueError(
                f"fold {self.fold_index}: calibration groups must be drawn from "
                f"the training groups; extra: {sorted(calibration - train)}"
            )
        if not self.valid and not self.invalid_reason:
            raise ValueError(
                f"fold {self.fold_index}: an invalid fold must state a reason"
            )
        return self

    def fit_groups(self) -> tuple[str, ...]:
        """Training groups excluding those reserved for calibration."""
        reserved = set(self.calibration_groups)
        return tuple(g for g in self.train_groups if g not in reserved)


class SplitManifest(BaseModel):
    """The complete, reproducible record of how a dataset was split."""

    model_config = {"extra": "forbid"}

    strategy: SplitStrategy
    strategy_reason: str = Field(
        min_length=1,
        description="Why this strategy was chosen over the alternative.",
    )
    group_field: GroupField
    group_field_reason: str = Field(min_length=1)

    group_count: int = Field(ge=1)
    n_splits: int = Field(ge=2)
    random_seed: int

    calibration_group_fraction: float = Field(default=0.0, ge=0.0, lt=1.0)
    folds: tuple[FoldAssignment, ...]

    audit_passed: bool = False
    audit_notes: tuple[str, ...] = ()


class ConfusionMatrix(BaseModel):
    """A confusion matrix stored with its labels, never as a bare array."""

    model_config = {"extra": "forbid"}

    labels: tuple[str, ...]
    rows_are: str = "true_label"
    columns_are: str = "predicted_label"
    counts: tuple[tuple[int, ...], ...]

    @model_validator(mode="after")
    def _check(self) -> Self:
        size = len(self.labels)
        if len(self.counts) != size:
            raise ValueError(
                f"confusion matrix has {len(self.counts)} rows but {size} labels"
            )
        for index, row in enumerate(self.counts):
            if len(row) != size:
                raise ValueError(
                    f"confusion matrix row {index} has {len(row)} entries but "
                    f"{size} labels"
                )
        return self

    def as_labelled_cells(self) -> dict[str, int]:
        """Flatten to ``{'true=<a>|predicted=<b>': count}``."""
        cells: dict[str, int] = {}
        for row_index, row in enumerate(self.counts):
            for column_index, count in enumerate(row):
                key = (
                    f"true={self.labels[row_index]}|"
                    f"predicted={self.labels[column_index]}"
                )
                cells[key] = count
        return cells


class PerClassMetrics(BaseModel):
    """Precision, recall, F1, and support for one class."""

    model_config = {"frozen": True}

    label: str
    support: int = Field(ge=0)
    precision: float | None = None
    recall: float | None = None
    f1: float | None = None


class CalibrationBin(BaseModel):
    """One reliability bin.

    Bins are equal-width over the predicted confidence, which is the
    maximum predicted class probability.  An empty bin is retained with
    ``count=0`` and null summaries rather than dropped, so the binning is
    reconstructible from the stored document.
    """

    model_config = {"frozen": True}

    bin_index: int = Field(ge=0)
    lower_edge: float = Field(ge=0.0, le=1.0)
    upper_edge: float = Field(ge=0.0, le=1.0)
    count: int = Field(ge=0)
    mean_confidence: float | None = None
    empirical_accuracy: float | None = None


class CalibrationMetrics(BaseModel):
    """Calibration quality for one probability set (calibrated or not)."""

    model_config = {"extra": "forbid"}

    label: str = Field(description="'uncalibrated' or the calibration method.")
    sample_count: int = Field(ge=0)
    brier_score: float | None = Field(
        default=None,
        description=(
            "Multiclass Brier score: mean over samples of the squared "
            "Euclidean distance between the predicted probability vector and "
            "the one-hot true vector. Range [0, 2]."
        ),
    )
    log_loss: float | None = None
    expected_calibration_error: float | None = None
    ece_bin_count: int | None = None
    ece_formula: str = (
        "ECE = sum_m (|B_m| / n) * |accuracy(B_m) - confidence(B_m)|, over "
        "equal-width bins of the maximum predicted class probability. "
        "accuracy(B_m) is the fraction of samples in bin m whose argmax "
        "prediction is correct; confidence(B_m) is the mean maximum "
        "predicted probability in bin m. Empty bins contribute zero."
    )
    bins: tuple[CalibrationBin, ...] = ()
    unavailable_reason: str | None = None
    note: str = (
        "A calibrated probability is not certainty and is not signal "
        "quality. It states how often outcomes of this kind occurred at "
        "this predicted probability in the evaluated folds."
    )


class ClassificationMetrics(BaseModel):
    """Classification metrics for one fold or one aggregate.

    A metric whose prerequisites are unmet is ``None`` with a stated
    reason.  It is never replaced with zero, because zero is a legitimate
    score and would be indistinguishable from "not computable".
    """

    model_config = {"extra": "forbid"}

    sample_count: int = Field(ge=0)
    independent_group_count: int = Field(ge=0)
    class_support: dict[str, int]

    accuracy: float | None = None
    balanced_accuracy: float | None = None
    macro_precision: float | None = None
    macro_recall: float | None = None
    macro_f1: float | None = None
    weighted_f1: float | None = None
    per_class: tuple[PerClassMetrics, ...] = ()
    confusion_matrix: ConfusionMatrix | None = None

    calibration: tuple[CalibrationMetrics, ...] = ()
    unavailable_metrics: dict[str, str] = Field(default_factory=dict)


class RegressionMetrics(BaseModel):
    """Regression metrics for one fold or one aggregate."""

    model_config = {"extra": "forbid"}

    sample_count: int = Field(ge=0)
    independent_group_count: int = Field(ge=0)

    mean_absolute_error: float | None = None
    root_mean_squared_error: float | None = None
    median_absolute_error: float | None = None
    r_squared: float | None = None

    target_mean: float | None = None
    target_std: float | None = None
    unavailable_metrics: dict[str, str] = Field(default_factory=dict)


class AggregateMetric(BaseModel):
    """A fold-level metric aggregated across folds.

    Aggregation is the unweighted mean over folds in which the metric was
    defined.  Folds are weighted equally rather than by size: a
    size-weighted mean silently lets one large participant dominate, which
    is the opposite of what grouped cross-validation is for.
    """

    model_config = {"frozen": True}

    name: str
    aggregation: str = "unweighted_mean_over_valid_folds"
    mean: float | None = None
    standard_deviation: float | None = None
    valid_fold_count: int = Field(ge=0)
    total_fold_count: int = Field(ge=0)
    fold_values: tuple[float | None, ...] = ()
    unavailable_reason: str | None = None


class ModelResult(BaseModel):
    """Everything recorded about one model on one dataset and split."""

    model_config = {"extra": "forbid"}

    model_name: str
    model_kind: str = Field(description="'dummy', 'linear', 'tree', or 'rule'.")
    is_software_check_baseline: bool = False
    parameters: dict[str, object] = Field(default_factory=dict)
    predictor_columns: tuple[str, ...] = ()

    fold_classification_metrics: tuple[ClassificationMetrics, ...] = ()
    fold_regression_metrics: tuple[RegressionMetrics, ...] = ()
    aggregate: tuple[AggregateMetric, ...] = ()
    aggregate_confusion_matrix: ConfusionMatrix | None = None

    failed_folds: dict[int, str] = Field(default_factory=dict)
    notes: tuple[str, ...] = ()


class MetricsDocument(BaseModel):
    """Top-level metrics document for one run.

    ``evaluation_mode`` and ``disclaimers`` are required.  A metrics file
    that does not say what kind of evidence it is (or is not) has no place
    in a research repository.
    """

    model_config = {"extra": "forbid"}

    run_id: str
    evaluation_mode: EvaluationMode
    scientific_evaluation_eligible: bool
    target_name: str
    task_type: str
    dataset_fingerprint: str
    group_field: str
    group_count: int = Field(ge=0)
    fold_count: int = Field(ge=0)
    random_seed: int

    results: tuple[ModelResult, ...] = ()
    disclaimers: tuple[str, ...]

    @model_validator(mode="after")
    def _check(self) -> Self:
        if not self.disclaimers:
            raise ValueError("a metrics document must carry at least one disclaimer")
        if self.evaluation_mode is EvaluationMode.SOFTWARE_SELF_CHECK:
            if self.scientific_evaluation_eligible:
                raise ValueError(
                    "a software self-check can never be scientifically eligible"
                )
            if not any(SOFTWARE_SELF_CHECK_BANNER in d for d in self.disclaimers):
                raise ValueError(
                    "a software self-check document must carry the banner "
                    f"{SOFTWARE_SELF_CHECK_BANNER!r}"
                )
        return self


