class AblationResult(BaseModel):
    """One feature-subset comparison, evaluated on the shared outer folds."""

    model_config = {"extra": "forbid"}

    ablation_name: str
    included_modalities: tuple[str, ...]
    feature_names: tuple[str, ...]
    available: bool = True
    unavailable_reason: str | None = None
    model_name: str | None = None
    aggregate: tuple[AggregateMetric, ...] = ()

    @model_validator(mode="after")
    def _check(self) -> Self:
        if not self.available and not self.unavailable_reason:
            raise ValueError(
                f"ablation {self.ablation_name!r} is unavailable and must state "
                "a reason"
            )
        return self


class AblationDocument(BaseModel):
    """All ablations for one run, sharing one set of outer folds."""

    model_config = {"extra": "forbid"}

    run_id: str
    evaluation_mode: EvaluationMode
    target_name: str
    shared_fold_count: int = Field(ge=0)
    split_strategy: str
    results: tuple[AblationResult, ...] = ()
    disclaimers: tuple[str, ...]
    note: str = (
        "These are feature-subset comparisons on identical folds. They are "
        "NOT a multimodal-fusion architecture: no modality mask, no "
        "quality-aware weighting, and no early/late fusion is implemented "
        "here. Fusion is Milestone 6."
    )


class RunManifest(BaseModel):
    """The manifest written atomically at the end of every run.

    A failed run still writes a manifest, with ``status=failed`` and the
    error recorded.  Silence would be indistinguishable from a run that
    never started, and an incomplete artifact set would otherwise read as
    a successful one.
    """

    model_config = {"extra": "forbid"}

    run_id: str
    engagevr_version: str
    python_version: str
    dependency_versions: dict[str, str]

    evaluation_mode: EvaluationMode
    scientific_evaluation_eligible: bool

    dataset_path: str
    dataset_fingerprint: str
    feature_catalog_version: str
    target_name: str
    task_type: str
    feature_set: tuple[str, ...]

    model_names: tuple[str, ...] = ()
    model_parameters: dict[str, dict[str, object]] = Field(default_factory=dict)

    split_strategy: str
    group_field: str
    group_count: int = Field(ge=0)
    fold_count: int = Field(ge=0)
    fold_assignments: dict[str, dict[str, tuple[str, ...]]] = Field(
        default_factory=dict
    )
    calibration_method: str | None = None

    configuration: dict[str, object] = Field(default_factory=dict)
    random_seed: int

    started_at_utc: datetime
    finished_at_utc: datetime
    status: RunStatus
    failure_reason: str | None = None

    artifact_checksums: dict[str, str] = Field(default_factory=dict)
    disclaimers: tuple[str, ...]

    @model_validator(mode="after")
    def _check(self) -> Self:
        if self.status is RunStatus.FAILED and not self.failure_reason:
            raise ValueError("a failed run must record a failure_reason")
        if self.status is RunStatus.COMPLETED and self.failure_reason:
            raise ValueError("a completed run must not record a failure_reason")
        return self
