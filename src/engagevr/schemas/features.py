class SubjectKind(enum.StrEnum):
    """Whether a row's subject is a real person or a generated stand-in."""

    PARTICIPANT = "participant"
    SYNTHETIC_SUBJECT = "synthetic_subject"


class TargetValue(BaseModel):
    """A target value plus the provenance that travels with it on the row."""

    model_config = {"extra": "forbid"}

    target_name: TargetName
    task_type: TaskType
    class_value: str | None = None
    numeric_value: float | None = None

    source_type: str = Field(min_length=1)
    source_instrument: str = Field(min_length=1)
    observed_at_utc: datetime
    interval_start_utc: datetime
    interval_end_utc: datetime
    synthetic_label: str | None = None
    provenance_notes: str = Field(min_length=1)
    scientific_evaluation_permitted: bool


class FeatureWindow(BaseModel):
    """One row of the windowed feature dataset.

    ``features`` and ``feature_available`` share the same key set: every
    catalog feature appears in both, so "absent from the dict" can never be
    confused with "measured as null".
    """

    model_config = {"extra": "forbid"}

    window_id: str = Field(min_length=1)
    session_id: str = Field(min_length=1)
    subject_id: str = Field(
        min_length=1,
        description="Pseudonymous subject identifier. Never a name or an email.",
    )
    subject_kind: SubjectKind
    experiment_condition: ExperimentCondition
    data_source: DataSource
    synthetic_label: str | None = None

    window_index: int = Field(ge=0)
    window_start_utc: datetime
    window_end_utc: datetime
    window_start_monotonic_seconds: float | None = None
    window_end_monotonic_seconds: float | None = None
    window_duration_seconds: float = Field(gt=0.0)
    window_step_seconds: float = Field(gt=0.0)
    windows_overlap: bool

    features: dict[str, float | None]
    categorical_features: dict[str, str | None] = Field(default_factory=dict)
    feature_available: dict[str, bool]
    modality_available: dict[str, bool]
    modality_quality: dict[str, float | None]
    targets: dict[str, TargetValue] = Field(default_factory=dict)

    feature_schema_version: str = FEATURE_SCHEMA_VERSION
    feature_catalog_version: str

    @model_validator(mode="after")
    def _check(self) -> Self:
        if self.window_end_utc <= self.window_start_utc:
            raise ValueError(
                f"window {self.window_id!r}: window_end_utc must be strictly "
                "after window_start_utc"
            )
        start = self.window_start_monotonic_seconds
        end = self.window_end_monotonic_seconds
        if (start is None) != (end is None):
            raise ValueError(
                f"window {self.window_id!r}: monotonic bounds must be supplied "
                "together or not at all"
            )
        if start is not None and end is not None and end <= start:
            raise ValueError(
                f"window {self.window_id!r}: monotonic end must be strictly "
                "after monotonic start"
            )
        shared = set(self.features) & set(self.categorical_features)
        if shared:
            raise ValueError(
                f"window {self.window_id!r}: features declared both numeric and "
                f"categorical: {sorted(shared)}"
            )
        declared = set(self.features) | set(self.categorical_features)
        missing_flags = declared - set(self.feature_available)
        if missing_flags:
            raise ValueError(
                f"window {self.window_id!r}: features without an availability "
                f"flag: {sorted(missing_flags)}"
            )
        extra_flags = set(self.feature_available) - declared
        if extra_flags:
            raise ValueError(
                f"window {self.window_id!r}: availability flags without a "
                f"feature: {sorted(extra_flags)}"
            )
        values: dict[str, object | None] = dict(self.features)
        values.update(self.categorical_features)
        for name, value in values.items():
            if value is None:
                if self.feature_available[name]:
                    raise ValueError(
                        f"window {self.window_id!r}: feature {name!r} is null but "
                        "marked available"
                    )
            elif not self.feature_available[name]:
                raise ValueError(
                    f"window {self.window_id!r}: feature {name!r} has a value but "
                    "is marked unavailable"
                )
        if self.data_source is DataSource.SYNTHETIC:
            if self.synthetic_label != SYNTHETIC_LABEL:
                raise ValueError(
                    f"window {self.window_id!r}: a synthetic row must carry "
                    f"synthetic_label={SYNTHETIC_LABEL!r}"
                )
            if self.subject_kind is not SubjectKind.SYNTHETIC_SUBJECT:
                raise ValueError(
                    f"window {self.window_id!r}: a synthetic row must have "
                    "subject_kind=synthetic_subject"
                )
        elif self.synthetic_label is not None:
            raise ValueError(
                f"window {self.window_id!r}: a non-synthetic row must leave "
                "synthetic_label unset"
            )
        return self


