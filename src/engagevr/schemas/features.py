"""Windowed-feature dataset schemas, column conventions, and metadata.

A *feature window* is one row of the modelling dataset: a fixed-duration
slice of one session, summarised into named scalar features, each paired
with an explicit availability flag.

Design rules encoded here
-------------------------
- Feature values, availability flags, signal quality, targets, and
  provenance live in **separate columns with separate prefixes**.  They
  are never merged, because "0.0" and "we could not measure it" are
  different observations and collapsing them destroys the difference.
- A missing measurement is ``None``.  It is never zero-filled at this
  layer; imputation is a modelling decision made inside a training fold.
- Poor signal quality is recorded as quality, never as a feature value
  and never as a low target value.
- Nothing that could identify a person is representable: there is no
  column for a name, an email, a frame, an image, or a landmark array,
  and :mod:`engagevr.features.validation` asserts none appears.
"""

from __future__ import annotations

import enum
from datetime import datetime
from typing import Self

from pydantic import BaseModel, Field, model_validator

from engagevr.schemas.session import DataSource, ExperimentCondition
from engagevr.schemas.targets import TARGET_DISCLAIMER, TargetName, TaskType

#: Version of the row schema (identity, time, and column conventions).
FEATURE_SCHEMA_VERSION = "1.0"

#: Permanent marker attached to every synthetic dataset row.
SYNTHETIC_LABEL = "SYNTHETIC"

#: Disclaimer persisted with every dataset built from synthetic input.
SYNTHETIC_DATASET_DISCLAIMER = (
    "SYNTHETIC DATASET. Every row was generated by software from a known "
    "data-generating process for the sole purpose of verifying that this "
    "pipeline is correct. No row describes a person. No metric computed "
    "from this dataset is experimental evidence, model accuracy, "
    "engagement validity, cognitive-load validity, or a performance claim, "
    "and none may be compared with a published result on real data."
)


# ---------------------------------------------------------------------------
# Column conventions
# ---------------------------------------------------------------------------

#: Measured or aggregated feature value. Nullable.
FEATURE_PREFIX = "feat__"
#: Per-feature availability flag. Never null.
AVAILABILITY_PREFIX = "avail__"
#: Whether a modality contributed anything to this window. Never null.
MODALITY_AVAILABLE_PREFIX = "modality_available__"
#: Modality signal quality in [0, 1]. Nullable when the modality is absent.
MODALITY_QUALITY_PREFIX = "modality_quality__"
#: Target value. Nullable: a dataset may carry no labels at all.
TARGET_PREFIX = "target__"
#: Target provenance field, ``target_meta__<target>__<field>``.
TARGET_META_PREFIX = "target_meta__"

#: Provenance fields carried per target, per row.
TARGET_META_FIELDS: tuple[str, ...] = (
    "task_type",
    "source_type",
    "source_instrument",
    "observed_at_utc",
    "interval_start_utc",
    "interval_end_utc",
    "synthetic_label",
    "provenance_notes",
    "scientific_evaluation_permitted",
)

#: Identity and grouping columns. Present on every row.
IDENTITY_COLUMNS: tuple[str, ...] = (
    "window_id",
    "session_id",
    "subject_id",
    "subject_kind",
    "experiment_condition",
    "data_source",
    "synthetic_label",
)

#: Window geometry and timing columns. Present on every row.
TIME_COLUMNS: tuple[str, ...] = (
    "window_index",
    "window_start_utc",
    "window_end_utc",
    "window_start_monotonic_seconds",
    "window_end_monotonic_seconds",
    "window_duration_seconds",
    "window_step_seconds",
    "windows_overlap",
)

#: Schema-version columns. Present on every row.
SCHEMA_COLUMNS: tuple[str, ...] = (
    "feature_schema_version",
    "feature_catalog_version",
)

#: Every column that is structurally forbidden from the predictor matrix.
#: Identifiers leak group membership, timestamps leak session ordering, and
#: target/provenance columns leak the answer.
NON_PREDICTOR_COLUMNS: frozenset[str] = frozenset(
    IDENTITY_COLUMNS + TIME_COLUMNS + SCHEMA_COLUMNS
)


def feature_column(name: str) -> str:
    """Column holding the value of feature ``name``."""
    return f"{FEATURE_PREFIX}{name}"


def availability_column(name: str) -> str:
    """Column holding the availability flag of feature ``name``."""
    return f"{AVAILABILITY_PREFIX}{name}"


def modality_available_column(modality: str) -> str:
    """Column holding whether ``modality`` contributed to a window."""
    return f"{MODALITY_AVAILABLE_PREFIX}{modality}"


def modality_quality_column(modality: str) -> str:
    """Column holding the quality score of ``modality``."""
    return f"{MODALITY_QUALITY_PREFIX}{modality}"


def target_column(target_name: TargetName | str) -> str:
    """Column holding the value of ``target_name``."""
    value = target_name.value if isinstance(target_name, TargetName) else target_name
    return f"{TARGET_PREFIX}{value}"


def target_meta_column(target_name: TargetName | str, field: str) -> str:
    """Column holding one provenance ``field`` of ``target_name``."""
    if field not in TARGET_META_FIELDS:
        raise ValueError(
            f"unknown target provenance field {field!r}; "
            f"known fields: {', '.join(TARGET_META_FIELDS)}"
        )
    value = target_name.value if isinstance(target_name, TargetName) else target_name
    return f"{TARGET_META_PREFIX}{value}__{field}"


def is_target_related_column(column: str) -> bool:
    """Whether ``column`` carries a target value or target provenance."""
    return column.startswith((TARGET_PREFIX, TARGET_META_PREFIX))


