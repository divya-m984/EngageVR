class FeatureModality(enum.StrEnum):
    """Feature groups used for ablation and for modality availability."""

    BEHAVIOURAL = "behavioural"
    HEAD_POSE = "head_pose"
    RPPG = "rppg"
    TASK = "task"
    QUALITY = "quality"


class FeatureDtype(enum.StrEnum):
    """Storage type of a feature column."""

    FLOAT = "float"
    INT = "int"
    BOOL = "bool"
    CATEGORY = "category"


class MissingBehaviour(enum.StrEnum):
    """What an absent measurement means for one feature.

    The distinction between ``NULL_WHEN_UNAVAILABLE`` and
    ``ZERO_WHEN_NO_EVENTS`` is the difference between "we could not look"
    and "we looked and there was nothing".  A blink count of 0 over a
    window in which a face was tracked throughout is a real observation;
    a blink count over a window with no face at all is not.
    """

    NULL_WHEN_UNAVAILABLE = "null_when_unavailable"
    NULL_WHEN_EVIDENCE_INSUFFICIENT = "null_when_evidence_insufficient"
    ZERO_WHEN_NO_EVENTS = "zero_when_no_events"


class FeatureSpec(BaseModel):
    """Catalog entry describing exactly one feature.

    A feature that has no entry here cannot appear in a dataset and cannot
    reach a model: :mod:`engagevr.training.preprocessing` rejects undeclared
    columns rather than passing them through.
    """

    model_config = {"frozen": True, "extra": "forbid"}

    canonical_name: str = Field(min_length=1)
    description: str = Field(min_length=1)
    modality: FeatureModality
    unit: str = Field(
        min_length=1,
        description="Physical or counting unit, or 'dimensionless'.",
    )
    aggregation_formula: str = Field(
        min_length=1,
        description="How the window value is computed from within-window evidence.",
    )
    minimum_evidence: str = Field(
        min_length=1,
        description="Evidence required before the value is computed at all.",
    )
    missing_behaviour: MissingBehaviour
    quality_dependency: str = Field(
        min_length=1,
        description="Which quality gate, if any, must pass first.",
    )
    permitted_predictor: bool = Field(
        description="Whether this feature may be used as a model input."
    )
    dtype: FeatureDtype = FeatureDtype.FLOAT
    value_minimum: float | None = None
    value_maximum: float | None = None

    @model_validator(mode="after")
    def _check(self) -> Self:
        if (
            self.value_minimum is not None
            and self.value_maximum is not None
            and self.value_minimum > self.value_maximum
        ):
            raise ValueError(
                f"feature {self.canonical_name!r}: value_minimum exceeds value_maximum"
            )
        if self.dtype is FeatureDtype.CATEGORY and self.permitted_predictor:
            raise ValueError(
                f"feature {self.canonical_name!r}: categorical features are not "
                "permitted predictors in this milestone"
            )
        return self


class FeatureCatalog(BaseModel):
    """An ordered, versioned collection of :class:`FeatureSpec` entries.

    Order is part of the contract.  It fixes column order in the dataset,
    which in turn is part of the dataset fingerprint, so a reordering is a
    detectable change rather than a silent one.
    """

    model_config = {"frozen": True}

    version: str = Field(min_length=1)
    entries: tuple[FeatureSpec, ...]

    @model_validator(mode="after")
    def _check(self) -> Self:
        names = [entry.canonical_name for entry in self.entries]
        duplicates = sorted({n for n in names if names.count(n) > 1})
        if duplicates:
            raise ValueError(f"duplicate feature names in catalog: {duplicates}")
        return self

    def names(self) -> tuple[str, ...]:
        """Canonical names, in catalog order."""
        return tuple(entry.canonical_name for entry in self.entries)

    def get(self, name: str) -> FeatureSpec:
        """Return the entry named ``name``.

        Raises
        ------
        KeyError
            If the feature is not in the catalog.
        """
        for entry in self.entries:
            if entry.canonical_name == name:
                return entry
        raise KeyError(f"feature {name!r} is not in feature catalog {self.version}")

    def by_modality(self, modality: FeatureModality) -> tuple[FeatureSpec, ...]:
        """Entries belonging to ``modality``, in catalog order."""
        return tuple(e for e in self.entries if e.modality is modality)

    def predictor_names(self) -> tuple[str, ...]:
        """Names of features permitted as model inputs, in catalog order."""
        return tuple(e.canonical_name for e in self.entries if e.permitted_predictor)

    def modalities(self) -> tuple[FeatureModality, ...]:
        """Modalities present in the catalog, in declaration order."""
        seen: list[FeatureModality] = []
        for entry in self.entries:
            if entry.modality not in seen:
                seen.append(entry.modality)
        return tuple(seen)


