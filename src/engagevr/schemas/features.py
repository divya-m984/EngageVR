class MissingnessSummary(BaseModel):
    """Per-feature missingness across a dataset."""

    model_config = {"frozen": True}

    feature_name: str
    missing_count: int = Field(ge=0)
    missing_pct: float = Field(ge=0.0, le=100.0)


class TargetSummary(BaseModel):
    """Class distribution or numeric summary for one target in a dataset."""

    model_config = {"frozen": True}

    target_name: str
    task_type: str
    labelled_row_count: int = Field(ge=0)
    class_distribution: dict[str, int] | None = None
    value_minimum: float | None = None
    value_maximum: float | None = None
    value_mean: float | None = None
    source_types: dict[str, int] = Field(default_factory=dict)
    scientific_evaluation_permitted: bool = False


class DatasetMetadata(BaseModel):
    """Deterministic provenance document written beside every dataset.

    ``created_at_utc`` is deliberately **excluded** from the canonical
    content used to compute ``dataset_fingerprint``: two equivalent builds
    of the same data must fingerprint identically, and a wall clock would
    make that impossible.
    """

    model_config = {"extra": "forbid"}

    dataset_schema_version: str = FEATURE_SCHEMA_VERSION
    feature_catalog_version: str

    row_count: int = Field(ge=0)
    feature_count: int = Field(ge=0)
    column_order: tuple[str, ...]

    subject_count: int = Field(ge=0)
    session_count: int = Field(ge=0)
    data_source_counts: dict[str, int]
    subject_kind_counts: dict[str, int]
    experiment_condition_counts: dict[str, int]

    window_duration_seconds: float = Field(gt=0.0)
    window_step_seconds: float = Field(gt=0.0)
    windows_overlap: bool

    missingness: tuple[MissingnessSummary, ...] = ()
    overall_missing_pct: float = Field(default=0.0, ge=0.0, le=100.0)
    targets: tuple[TargetSummary, ...] = ()

    creation_configuration: dict[str, object] = Field(default_factory=dict)
    random_seed: int | None = Field(
        default=None, description="Set only for generated datasets."
    )
    input_session_fingerprints: dict[str, str] = Field(default_factory=dict)

    dataset_fingerprint: str = Field(
        min_length=64,
        max_length=64,
        description="SHA-256 over canonical row content, column order, and schema.",
    )
    fingerprint_algorithm: str = "sha256"
    fingerprint_inputs: str = (
        "column order, schema versions, feature catalog version, window "
        "geometry, and every row's canonical value list. Excludes "
        "created_at_utc and any other wall-clock value."
    )

    created_at_utc: datetime
    scientific_evaluation_eligible: bool
    disclaimers: tuple[str, ...] = (TARGET_DISCLAIMER,)
