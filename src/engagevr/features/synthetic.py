def _apply_structural_relationships(
    values: dict[str, float | None], config: SyntheticDatasetConfig
) -> None:
    """Impose the arithmetic relationships that real aggregation would.

    These produce genuine collinearity: the three response proportions sum
    to one, the minimum eye-openness never exceeds the mean, counts are
    consistent with their proportions, and the reaction-time order
    statistics are ordered. A generator that ignored these would produce a
    table no aggregation step could ever have emitted.
    """
    correct = _as_float(values["task_correct_proportion"])
    timeout = _as_float(values["task_timeout_proportion"])
    total = correct + timeout
    if total > 1.0:
        correct /= total
        timeout /= total
    values["task_correct_proportion"] = correct
    values["task_timeout_proportion"] = timeout
    values["task_incorrect_proportion"] = max(0.0, 1.0 - correct - timeout)

    attempted = max(1.0, _as_float(values["task_attempted_trials"]))
    values["task_attempted_trials"] = attempted
    values["task_completed_trials"] = min(
        attempted, _as_float(values["task_completed_trials"])
    )
    values["task_correct_count"] = float(round(attempted * correct))
    values["task_timeout_count"] = float(round(attempted * timeout))
    values["task_incorrect_count"] = max(
        0.0,
        attempted
        - _as_float(values["task_correct_count"])
        - _as_float(values["task_timeout_count"]),
    )

    mean_ear = _as_float(values["eye_openness_proxy_mean"])
    values["eye_openness_proxy_min"] = min(
        mean_ear, _as_float(values["eye_openness_proxy_min"])
    )

    rt_mean = _as_float(values["task_reaction_time_mean_ms"])
    values["task_reaction_time_min_ms"] = min(
        rt_mean, _as_float(values["task_reaction_time_min_ms"])
    )
    values["task_reaction_time_max_ms"] = max(
        rt_mean, _as_float(values["task_reaction_time_max_ms"])
    )
    values["task_reaction_time_median_ms"] = float(
        np.clip(
            _as_float(values["task_reaction_time_median_ms"]),
            _as_float(values["task_reaction_time_min_ms"]),
            _as_float(values["task_reaction_time_max_ms"]),
        )
    )

    duration_minutes = config.window_duration_seconds / 60.0
    rate = _as_float(values["blink_proxy_rate_per_min"])
    values["blink_proxy_count"] = float(round(rate * duration_minutes))

    yaw_sd = _as_float(values["head_yaw_sd_deg"])
    values["head_yaw_range_deg"] = max(
        _as_float(values["head_yaw_range_deg"]), 2.0 * yaw_sd
    )
    pitch_sd = _as_float(values["head_pitch_sd_deg"])
    values["head_pitch_range_deg"] = max(
        _as_float(values["head_pitch_range_deg"]), 2.0 * pitch_sd
    )


def _as_float(value: float | None) -> float:
    if value is None:  # pragma: no cover - structural step runs before dropout
        raise ValueError("structural relationships run before any value is cleared")
    return float(value)


def _modality_quality(modality: str, values: dict[str, float | None]) -> float | None:
    """Quality score reported for one modality of a generated window."""
    if modality == "rppg":
        return values.get("rppg_quality_score")
    if modality == "behavioural":
        presence = values.get("face_presence_pct")
        return None if presence is None else presence / 100.0
    if modality == "head_pose":
        pct = values.get("head_pose_available_pct")
        return None if pct is None else pct / 100.0
    if modality == "quality":
        blurry = values.get("capture_blurry_pct")
        return None if blurry is None else max(0.0, 1.0 - blurry / 100.0)
    return 1.0
