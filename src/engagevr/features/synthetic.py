"""Deterministic SYNTHETIC windowed-feature generator for software verification.

Purpose
-------
This generator exists so that the modelling pipeline can be tested end to
end **without any participant data**.  Every row it produces is labelled
``SYNTHETIC`` permanently, every target it produces sets
``scientific_evaluation_permitted=False``, and no number computed from its
output is evidence about a person.

The hidden data-generating process
----------------------------------
Two latent variables drive each window and are **never emitted as
columns**:

- ``E`` — a latent "engagement" value in ``[0, 1]``;
- ``L`` — a latent "cognitive load" value in ``[0, 1]``.

They are built as::

    e_raw = e_base + subject_effect_e + session_effect_e + drift_e(t) + ar_e(t)
    l_raw = l_base + subject_effect_l + session_effect_l + drift_l(t)
            + ar_l(t) - coupling * (e_raw - e_base)
    E = clip(e_raw, 0, 1)
    L = clip(l_raw, 0, 1)

where ``subject_effect_*`` is one draw per synthetic subject (a **group
effect**), ``session_effect_*`` is one draw per session (a **session
effect**), ``drift_*`` is a linear trend across the session, ``ar_*`` is a
first-order autoregressive noise process across windows, and ``coupling``
makes load mildly anti-correlated with engagement.

Every observable feature is then drawn as::

    value = base + engagement_coefficient * (E - 0.5)
                 + load_coefficient * (L - 0.5)
                 + Normal(0, noise_sd)

clipped to the feature's catalog range.  A feature whose coefficients are
both zero is **irrelevant by construction** — it carries no information
about either latent — and several such features are included deliberately
so that feature selection and interpretation have something to get wrong.
A handful of features are additionally derived from others (for example,
the incorrect-response proportion is one minus the correct and timeout
proportions), which produces genuine collinearity.

Targets are noisy observations of the latents::

    engagement_score = clip(E + Normal(0, label_noise_sd), 0, 1)
    engagement_class = threshold(engagement_score, class_thresholds)

so a perfect score is not attainable even in principle.  The generator is
**not** tuned to make any model look good and is not tuned toward any
model family: the relationships are additive and monotone, which suits a
linear model, while the missingness, the clipping, and the class
thresholds introduce non-linearity, which suits a tree.  No choice here
was made after looking at a result.

What this is not
----------------
This is not a model of human behaviour, not a simulation of physiology,
and not a substitute for data.  It exercises code paths.
"""

