#: Keyed lookup for page captions.
TERMINOLOGY_BY_KEY: dict[str, Term] = {term.key: term for term in TERMINOLOGY}


def term_caption(key: str) -> str:
    """One-line caption naming a quantity and what it is not.

    Pages call this instead of writing a caption by hand, so the same
    quantity is described the same way on every page it appears on.
    """
    term = TERMINOLOGY_BY_KEY[key]
    negations = ", ".join(term.is_not)
    return f"{term.display_name}. {term.definition} It is {negations}."


