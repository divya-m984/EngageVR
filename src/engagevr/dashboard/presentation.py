"""Static presentation content: terminology, limitations, disclaimers.

Two things live here rather than in the pages.

**The vocabulary.**  The project keeps several quantities separate that a
dashboard is under constant pressure to merge: signal quality, calibrated
classification confidence, ensemble disagreement, predictive entropy,
probability margin, and regression interval width.  Each is a different
question about a different object, and a shared label would be the first
step to a shared axis.  :data:`TERMINOLOGY` states each one's display
name and what it is not, and the pages read from it rather than typing a
caption by hand.

**The limitations.**  These are typed records, not Markdown scraped at
run time.  A page that parses prose renders nothing when the prose is
reworded, and the limitations page is the one that must never quietly go
blank.  The records carry a document reference so the reader can open the
full statement.
"""

