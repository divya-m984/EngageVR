#: Display label for each recorded ``data_source`` value, in words.
#:
#: The recorded strings are the project's own
#: :class:`~engagevr.schemas.session.DataSource` members plus the
#: catalogue's ``"mixed"``.  They are terse, and ``public_dataset`` in a
#: monospaced cell is easy to skim past, so every provenance surface
#: renders this label beside the raw value rather than instead of it.
#: The raw value is what the artifact recorded; the label is what a
#: reader must not miss.
DATA_SOURCE_LABELS: dict[str, str] = {
    "synthetic": "SYNTHETIC",
    "public_dataset": "PUBLIC",
    "live": "LIVE",
    "mixed": "MIXED",
}

#: What each data source does and does not establish.
#:
#: Each entry ends on the same point, because it is the one a reader is
#: most likely to supply for themselves in the wrong direction: where the
#: bytes came from is not a statement that a study was designed,
#: labelled, approved, or validated.  Neither *public* nor *live* is a
#: shortcut to scientific eligibility.
DATA_SOURCE_NOTES: dict[str, str] = {
    "synthetic": (
        "SYNTHETIC data source: generated by this repository from a "
        "data-generating process it also wrote. It is a software "
        "self-check and is never scientific evidence about any person."
    ),
    "public_dataset": (
        "PUBLIC data source: content originating in a public research "
        "dataset. Being public does not make anything here scientifically "
        "eligible. Eligibility is declared by the artifact, this "
        "repository has validated nothing, and a public corpus says where "
        "the bytes came from, not that a study was designed, labelled, "
        "approved, or validated for this target."
    ),
    "live": (
        "LIVE data source: content recorded from a session running on this "
        "machine. Being live does not make it scientifically eligible; "
        "'live' says where the bytes came from, not that a study was "
        "designed, labelled, approved, or validated."
    ),
    "mixed": (
        "MIXED data sources: this artifact records more than one origin. "
        "The strictest reading present applies, and no part of it becomes "
        "scientifically eligible by being mixed with another."
    ),
}

#: Said where a data source was recorded that this vocabulary has no
#: wording for. The value is shown, never guessed at or normalised away.
UNKNOWN_DATA_SOURCE_NOTE = (
    "This data source is not one this dashboard has wording for. It is "
    "displayed exactly as recorded and is not interpreted. Nothing about "
    "an unrecognised source makes it scientifically eligible."
)

#: Said where nothing recorded a data source at all.
ABSENT_DATA_SOURCE_LABEL = "Unavailable — no data source is recorded"


def data_source_label(value: str | None) -> str:
    """The display label for one recorded data-source string.

    Returns the label and the recorded value together.  Showing only the
    label would hide what the artifact actually says; showing only the
    recorded value leaves ``public_dataset`` to be noticed rather than
    read.
    """
    if value is None or not value.strip():
        return ABSENT_DATA_SOURCE_LABEL
    recorded = value.strip()
    label = DATA_SOURCE_LABELS.get(recorded)
    if label is None:
        return f"UNRECOGNISED (recorded as {recorded!r})"
    return f"{label} (recorded as {recorded!r})"


def data_source_statement(value: str | None) -> str:
    """What one recorded data source does and does not establish."""
    if value is None or not value.strip():
        return (
            "No data source is recorded for this evidence. Its absence is "
            "stated rather than filled in, and nothing here is "
            "scientifically eligible."
        )
    return DATA_SOURCE_NOTES.get(value.strip(), UNKNOWN_DATA_SOURCE_NOTE)


def data_source_statements(values: Sequence[str]) -> tuple[str, ...]:
    """The statements for every recorded data source, deduplicated in order."""
    seen: list[str] = []
    for value in values:
        statement = data_source_statement(value)
        if statement not in seen:
            seen.append(statement)
    return tuple(seen)


